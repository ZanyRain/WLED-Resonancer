/*
 * Resonancer usermod - LumaFlow input, WLED output.
 *
 * The usermod is split into two independent halves:
 *
 *   INPUT   LumaFlow frames (serial, UDP, BLE) carry 10 channels
 *           (CH0..CH9). Every WLED segment may subscribe to one channel. A
 *           subscribed segment receives the channel colour in its primary
 *           colour slot and, when the channel asks for it, a blinking WLED
 *           effect that provides the timing. Segments that are not subscribed
 *           are never touched.
 *
 *   OUTPUT  Every output channel reads the colour of one upstream segment
 *           (mirror image of the input mapping) and hands it to a local output
 *           device. The output half is only compiled in when
 *           RESONANCER_ENABLE_RF is set; its implementation lives outside this
 *           repository.
 *
 * See readme.md for the build switches.
 */

