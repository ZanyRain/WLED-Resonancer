void ResonancerUsermod::addToJsonState(JsonObject& root) {
  if (!initDone) return;
  JsonObject um = root[FPSTR(_name)];
  if (um.isNull()) um = root.createNestedObject(FPSTR(_name));
  um[FPSTR(_enabled)] = enabled;
  um[FPSTR(_comm)] = commMode;
  um[FPSTR(_outputEnabled)] = outputEnabled;
}

void ResonancerUsermod::readFromJsonState(JsonObject& root) {
  if (!initDone) return;
  JsonObject um = root[FPSTR(_name)];
  if (!um.isNull()) {
    getJsonValue(um[FPSTR(_enabled)], enabled);
    bool wanted = outputEnabled;
    if (getJsonValue(um[FPSTR(_outputEnabled)], wanted)) {
      // The switch is the user's intent: it is stored even while the licence does not
      // allow operation, and the output comes up by itself once the licence arrives.
      outputEnabled = wanted;
      if (wanted) outputArmed = true;
    }
    // Explicit resume: {"Resonancer":{"stream":true}} lifts the hold a preset set, which is
    // the programmatic counterpart of toggling the output switch.
    bool resume = false;
    if (getJsonValue(um[F("stream")], resume) && resume) outputHeld = false;

    // Preset command: {"Resonancer":{"oem":"red"}} uses the stable key of the button,
    // {"Resonancer":{"oem":3}} the slot it happens to have. Both are queued and served
    // in loop(); nothing is sent from the HTTP task.
    JsonVariant oem = um[FPSTR(_oem)];
    if (oem.is<const char*>())      requestOem(ResonancerUi::oemKeyIndex(oem.as<const char*>()));
    else if (oem.is<int>())         requestOem((int8_t)oem.as<int>());
  }

  // Transport for LumaFlow frames forwarded as hex text (HTTP/WS/MQTT clients).
  JsonObject lf = root["lumaflow"];
  if (!lf.isNull()) {
    const char* cmd = lf["cmd"] | "";
    const char* data = lf["data"] | "";
    const uint8_t cmdId = (strcmp(cmd, "stream") == 0) ? LumaFlow::CMD_STREAM
                        : (strcmp(cmd, "auth") == 0) ? LumaFlow::CMD_AUTH : 0;
    if (cmdId != 0) onLumaFlowFrameHex(cmdId, data);
  }
}

void ResonancerUsermod::addToJsonInfo(JsonObject& root) {
  JsonObject user = root["u"];
  if (user.isNull()) user = root.createNestedObject("u");

  char buf[144];
  snprintf_P(buf, sizeof(buf), PSTR("%s, %lu frames, %lu dup, %lu errors"),
             enabled ? "active" : "inactive",
             (unsigned long)framesReceived, (unsigned long)framesDuplicate,
             (unsigned long)framesRejected);
  JsonArray arr = user.createNestedArray(FPSTR(_name));
  arr.add(buf);


  if (inStream) arr.add(F(" streaming"));
#if RESONANCER_ENABLE_BLE
  if (commMode == COMM_BLE) {
    JsonArray ble = user.createNestedArray(F("BLE"));
    ble.add(ResonancerBle::isConnected() ? F("connected")
           : bleActive ? F("advertising") : F("off"));
    // A usermod row is rendered as value + unit, and anything beyond that is dropped, so the
    // policy and the forced modem sleep share the unit slot.
    char policy[64];
    snprintf_P(policy, sizeof(policy), PSTR(", %s%s"),
               bleCoexist == BLE_COEX_WIFI_FIRST ? "WiFi first"
               : bleCoexist == BLE_COEX_BLE_FIRST ? "BLE first" : "both",
               ResonancerBle::isModemSleepForced() ? ", WiFi sleep on" : "");
    ble.add(policy);
  }
#endif

  // Output rows. Only a build with an output implementation shows them: in a build without one
  // the reference backend still runs (and can be driven through the JSON API), but there is
  // nothing here a user should read as a device.
#if RESONANCER_ENABLE_RF
  // The info page renders a usermod row as value + unit and drops everything beyond that, so
  // this row has exactly two elements: the bare state (which the settings page tests to decide
  // whether a preset may run) and a unit that carries the details and the switch. "held by
  // preset" and "idle, nothing mapped" are surfaced because they explain an output that is up
  // but silent.
  JsonArray out = user.createNestedArray(F("Output"));
  const char* device = (rfDevice != nullptr) ? rfDevice->getName() : "unavailable";
  out.add(FPSTR(statusText()));
  const char* note = !outputEnabled ? ""
                   : outputHeld ? ", held by preset"
                   : (!anyInputSubscribed() || !anyOutputMapped()) ? ", idle, nothing mapped" : "";
  char detail[96];
  snprintf_P(detail, sizeof(detail), PSTR(", %s, %lu packets%s"),
             device, (unsigned long)packetsSent, note);

  // Manual switch: starts an output that is only promised (switch on, nothing started it in
  // this boot) and toggles the switch otherwise, so one click is always the action the user
  // expects from what the row shows.
  const bool postOn = !outputEnabled || !outputArmed;
  String unit = detail;
  unit += F("<button class=\"btn btn-xs\" onclick=\"requestJson({Resonancer:{outputEnabled:");
  unit += postOn ? F("true}});\">") : F("false}});\">");
  unit += outputEnabled ? F("<i class=\"icons on\">&#xe08f;</i>") : F("<i class=\"icons off\">&#xe08f;</i>");
  unit += F("</button>");
  out.add(unit);

  // Result of the last preset command, added only once there was one: the settings page polls
  // this row, and the row is what makes a click verifiable instead of a promise. A row that
  // only ever says "nothing happened yet" is noise.
  if (oemResult != OEM_NONE) {
    JsonArray pre = user.createNestedArray(F("Preset"));
    const ResonancerUi::OemKey* lastKey = ResonancerUi::oemKeyAt(oemResultSlot);
    char res[64];
    if ((oemResult == OEM_SENT || oemResult == OEM_QUEUED) && lastKey != nullptr) snprintf_P(res, sizeof(res), PSTR("%s: %s"), oemResultText(), lastKey->label);
    else snprintf_P(res, sizeof(res), PSTR("%s"), oemResultText());
    pre.add(res);
  }

  // Radio diagnostics. transmitted/submitted shows whether the radio keeps up, the queue wait
  // how stale a packet is when it goes on the air, and the bring-ups whether the output is
  // being rebuilt. One string: the info page only renders value + unit.
  if (rfDevice != nullptr) {
    const uint32_t txUs = rfDevice->lastTxMicros();
    const uint32_t configs = rfDevice->configCount();
    if (txUs > 0 || configs > 0) {
      JsonArray rf = user.createNestedArray(F("RF"));
      char txt[160];
      const uint32_t late = rfDevice->txTimeouts();
      snprintf_P(txt, sizeof(txt), PSTR("%lu/%lu pkt, %lu pkt/s, tx %lu ms, queue %lu ms, %lu bring-ups%s"),
                 (unsigned long)rfDevice->txCount(), (unsigned long)packetsSent,
                 (unsigned long)rfDevice->txRate(),
                 (unsigned long)(txUs / 1000), (unsigned long)rfDevice->lastQueueMs(),
                 (unsigned long)configs, late > 0 ? ", late" : "");
      rf.add(txt);
    }
  }
#endif  // RESONANCER_ENABLE_RF

  // Boot row: the reset reason is what tells "the strip flashed" apart from "the device
  // rebooted", which is the first question when the output hardware is on the same rail.
  JsonArray boot = user.createNestedArray(F("Boot"));
  char bootTxt[48];
  snprintf_P(bootTxt, sizeof(bootTxt), PSTR("%s, %lu s up"),
             resetReasonText(), (unsigned long)(millis() / 1000));
  boot.add(bootTxt);
}

void ResonancerUsermod::addToConfig(JsonObject& root) {
  JsonObject top = root.createNestedObject(FPSTR(_name));
  top[FPSTR(_enabled)] = enabled;
  top[FPSTR(_comm)] = commMode;
  top[FPSTR(_udpPort)] = udpPort;
  top[FPSTR(_bleSuffix)] = bleSuffix;
  top[FPSTR(_bleCoexist)] = bleCoexist;

  // One entry per existing WLED segment holding the subscribed LumaFlow channel,
  // -1 = the segment keeps its own effect. The list therefore grows and shrinks
  // with the segment layout; the next save after adding segments writes the new
  // rows and the settings page shows them from then on.
  JsonArray map = top.createNestedArray(FPSTR(_segChannel));
  const uint8_t segCount = strip.getSegmentsNum();
  for (uint8_t s = 0; s < segCount; s++) {
    map.add((segChannel[s] < CHANNEL_COUNT) ? (int)segChannel[s] : -1);
  }

  // Output half. Serialised only when the output half is compiled in: without it
  // the settings page must not show any output option at all, and omitting the
  // fields is what keeps them out of both the page and the stored configuration.
#if RESONANCER_ENABLE_RF
  // The key order is the order of the settings page, so the output channel
  // mapping is serialised last: it ends up between the pins and the OEM control.
  top[FPSTR(_outputEnabled)] = outputEnabled;
  top[FPSTR(_rfFreq)] = rfConfig.rf_freq;
  JsonArray pins = top.createNestedArray(FPSTR(_rfPins));
  pins.add((int)rfSck); pins.add((int)rfMiso); pins.add((int)rfMosi);
  pins.add((int)rfSs);  pins.add((int)rfGd0);  pins.add((int)rfGd2);
  JsonArray outMap = top.createNestedArray(FPSTR(_outSeg));
  for (uint8_t ch = 0; ch < CHANNEL_COUNT; ch++) {
    outMap.add((outChannelSegment[ch] == 0xFF) ? -1 : (int)outChannelSegment[ch]);
  }
#endif
}

bool ResonancerUsermod::readFromConfig(JsonObject& root) {
  JsonObject top = root[FPSTR(_name)];
  if (top.isNull()) return false;
  bool complete = true;

  // A key is only read when it is present. getJsonValue(key, dest, default) assigns the
  // default for a missing key, which would turn a partial write (a POST carrying only
  // some of the fields) into a reset of everything it does not mention.
  if (top.containsKey(FPSTR(_enabled)))    getJsonValue(top[FPSTR(_enabled)], enabled);       else complete = false;
  if (top.containsKey(FPSTR(_comm)))       getJsonValue(top[FPSTR(_comm)], commMode);         else complete = false;
  if (top.containsKey(FPSTR(_udpPort)))    getJsonValue(top[FPSTR(_udpPort)], udpPort);       else complete = false;
  if (top.containsKey(FPSTR(_bleCoexist))) getJsonValue(top[FPSTR(_bleCoexist)], bleCoexist); else complete = false;

  // getJsonValue() cannot assign into a fixed size char array, so the string is read
  // explicitly and copied with a bound.
  if (top.containsKey(FPSTR(_bleSuffix))) {
    const char* suffix = top[FPSTR(_bleSuffix)] | "";
    strncpy(bleSuffix, suffix, sizeof(bleSuffix) - 1);
    bleSuffix[sizeof(bleSuffix) - 1] = '\0';
  } else {
    complete = false;
  }

  // Rebuild the subscriptions from scratch so removed entries cannot survive. Segments
  // that are currently driven by the usermod are handed back first, otherwise their
  // original settings would be dropped with the backup and they would keep the usermod
  // effect forever. The rebuild only happens when the list is part of the write.
  if (top.containsKey(FPSTR(_segChannel))) {
    outputHeld = false;       // the user reconfigured the bridge: resume streaming
    releaseAllSegments();
    for (uint8_t s = 0; s < MAX_NUM_SEGMENTS; s++) {
      segChannel[s] = SEGMENT_UNMAPPED;
      appliedFunction[s] = 0xFF;
      appliedColor[s] = 0xFFFFFFFF;
    }
    JsonArray map = top[FPSTR(_segChannel)];
    const uint8_t n = (map.size() < MAX_NUM_SEGMENTS) ? (uint8_t)map.size() : MAX_NUM_SEGMENTS;
    for (uint8_t s = 0; s < n; s++) {
      const int ch = map[s] | -1;
      if (ch >= 0 && ch < CHANNEL_COUNT) segChannel[s] = (uint8_t)ch;
    }
  } else {
    complete = false;
  }

  // Output half. Serialised only when the output half is compiled in, so it is read
  // back under the same condition.
#if RESONANCER_ENABLE_RF
  // A settings save stores the user's intent only. It deliberately does not start the
  // output: a save must never reset a device whose output cannot come up. Starting is
  // always an explicit action (the info page button or the JSON API) or the host's
  // AUTH frame.
  if (top.containsKey(FPSTR(_outputEnabled))) getJsonValue(top[FPSTR(_outputEnabled)], outputEnabled); else complete = false;

  float freq = rfConfig.rf_freq;
  if (top.containsKey(FPSTR(_rfFreq))) {
    getJsonValue(top[FPSTR(_rfFreq)], freq);
  } else {
    complete = false;
  }
  if (freq <= 0.0f) { freq = RESONANCER_DEFAULT_RF_FREQ; complete = false; }
  // The device holds the frequency it was set up with, so a change has to be pushed
  // through changeRuntimeConfig() in loop().
  if (freq != rfConfig.rf_freq) rfConfigDirty = true;
  rfConfig.rf_freq = freq;

  if (top.containsKey(FPSTR(_outSeg))) {
    for (uint8_t ch = 0; ch < CHANNEL_COUNT; ch++) outChannelSegment[ch] = 0xFF;
    JsonArray outMap = top[FPSTR(_outSeg)];
    const uint8_t n = (outMap.size() < CHANNEL_COUNT) ? (uint8_t)outMap.size() : CHANNEL_COUNT;
    for (uint8_t ch = 0; ch < n; ch++) {
      const int seg = outMap[ch] | -1;
      // Stored as a byte, so an out of range entry would wrap onto another segment.
      // Entries that do not name an existing segment are dropped.
      if (seg >= 0 && seg < MAX_NUM_SEGMENTS) outChannelSegment[ch] = (uint8_t)seg;
    }
  } else {
    complete = false;
  }

  if (top.containsKey(FPSTR(_rfPins))) {
    JsonArray pins = top[FPSTR(_rfPins)];
    if (pins.size() < 6) {
      complete = false;
    } else {
      int values[6];
      for (uint8_t i = 0; i < 6; i++) values[i] = pins[i] | -1;
      rfSck = values[0]; rfMiso = values[1]; rfMosi = values[2];
      rfSs  = values[3]; rfGd0  = values[4]; rfGd2  = values[5];
      rfConfigDirty = true;         // pins changed, rebuild in loop()
    }
  } else {
    complete = false;
  }
#endif

  return complete;
}

/** Adapter between the library's callback and the member function that fills it. */
static void buildPageTrampoline(JsonObject& page, void* ctx) {
  static_cast<ResonancerUsermod*>(ctx)->buildUikitPage(page);
}

/**
 * Settings page metadata.
 *
 * Since the page is data driven (see resonancer_uikit.js and resonancer_uikit.cpp) this
 * is only the hand-off: build the page description and let the engine decorate the form
 * WLED generated. The previous implementation emitted the decoration as hand written
 * JavaScript from here, which made every field name appear in three places.
 */
void ResonancerUsermod::appendConfigData(Print& settingsScript) {
  ResonancerUi::emit(settingsScript, buildPageTrampoline, this);
}

/**
 * Describe the settings page: components, restricting rules, hints and checks.
 *
 * Field names come from the constants above, so a field cannot be renamed in one place
 * and stay stale here. Ids are relative; the engine prefixes them with the usermod name
 * and adds the '[]' suffix of repeated fields. An id starting with '#' belongs to a
 * widget this usermod draws itself and has no config field behind it.
 */
void ResonancerUsermod::buildUikitPage(JsonObject& page) {
  using namespace ResonancerUi;

  page[F("prefix")] = _name;
  page[F("anchor")] = _outputEnabled;

  // --- input half ---------------------------------------------------------
  component(page, _enabled, "input");

  JsonObject proto = component(page, _comm, "input", W_DROPDOWN);
  proto[F("label")] = F("Protocol");
  option(proto, "Serial", COMM_SERIAL);
  option(proto, "UDP", COMM_UDP);
#if RESONANCER_ENABLE_BLE
  option(proto, "BLE", COMM_BLE);
#else
  option(proto, "BLE (not compiled in)", COMM_BLE, true);
#endif

  // Only the selected transport shows its own settings.
  rule(page, _comm, OP_NE, "1", _udpPort,    PROP_VISIBLE, false, "UDP only");
  rule(page, _comm, OP_NE, "2", _bleSuffix,  PROP_VISIBLE, false, "BLE only");
  rule(page, _comm, OP_NE, "2", _bleCoexist, PROP_VISIBLE, false, "BLE only");
  rule(page, _comm, OP_EQ, "2", _bleSuffix,  PROP_REQUIRED, true, "BLE needs a suffix");

#if RESONANCER_ENABLE_RF
  hint(page, _comm, -1, HINT_INFO,
       "<b>One transport at a time.</b> The output half is independent and keeps running.");
#else
  hint(page, _comm, -1, HINT_INFO,
       "<b>One transport at a time.</b> The other transports stay idle while one is selected.");
#endif

  component(page, _udpPort, "input")[F("label")] = F("UDP port");
  hint(page, _udpPort, -1, HINT_INFO,
       "The host sends to <b>32712</b> and rejects any other port. Independent of the WLED ports (sync, NTP, Hyperion).");

  component(page, _bleSuffix, "input")[F("label")] = F("BLE suffix");
  hint(page, _bleSuffix, -1, HINT_INFO,
       "Advertised as <b>LumaFlow&lt;suffix&gt;</b>, e.g. <b>LumaFlow-66CCFF</b>. Give each device its own suffix.");

  JsonObject coex = component(page, _bleCoexist, "input", W_DROPDOWN);
  coex[F("label")] = F("BLE / WiFi");
  option(coex, "Allow both (WiFi + BLE share the radio)", BLE_COEX_ALLOW_BOTH);
  option(coex, "WiFi first (pause BLE advertising while the web UI is open)", BLE_COEX_WIFI_FIRST);
  option(coex, "BLE first (keep advertising while streaming)", BLE_COEX_BLE_FIRST);
  // The trade-off is made explicit instead of being implicit.
  hint(page, _bleCoexist, -1, HINT_WARN,
       "One 2.4 GHz radio for both. Pausing BLE advertising only delays discovery: the host finds the device again once the web UI is idle.");
  // Hard requirement, not a policy: the ESP32 aborts when the Bluetooth controller
  // starts while WiFi modem sleep is off, and WLED disables modem sleep by default.
  hint(page, _bleCoexist, -1, HINT_ERROR,
       "<b>WiFi modem sleep is forced on while BLE is selected</b> - the ESP32 aborts without it. The web UI stays usable, just slightly slower.");

  // Subscription of each WLED segment to a LumaFlow channel: one row per segment.
  JsonObject segRows = arrayComponent(page, _segChannel, "input", W_DROPDOWN);
  segRows[F("heading")] = F("Input mapping");
  segRows[F("captionEach")] = F("SEG$i");
  option(segRows, "-", -1);
  for (uint8_t ch = 0; ch < CHANNEL_COUNT; ch++) {
    char label[12];
    snprintf_P(label, sizeof(label), PSTR("CH%u"), (unsigned)ch);
    option(segRows, label, (int16_t)ch);
  }

  // --- output half --------------------------------------------------------
  // Only emitted when the output half is compiled in. Without it the settings page must
  // not show any output option at all, which is handled by addToConfig() omitting the
  // fields in that case.
#if RESONANCER_ENABLE_RF
  component(page, _outputEnabled, "input")[F("heading")] = F("Output");

  // Everything that needs the output hardware follows the switch. The preset grid below
  // is deliberately not part of this: it stays visible and simply refuses to run while
  // the output is off, so one click can never start a device by accident.
  rule(page, _outputEnabled, OP_FALSE, nullptr, _rfFreq,   PROP_VISIBLE, false, "Output is off");
  rule(page, _outputEnabled, OP_FALSE, nullptr, _rfPins,   PROP_VISIBLE, false, "Output is off");
  rule(page, _outputEnabled, OP_FALSE, nullptr, _outSeg,   PROP_VISIBLE, false, "Output is off");
  rule(page, _outputEnabled, OP_FALSE, nullptr, "#outFold", PROP_VISIBLE, false, "Output is off");

  component(page, _rfFreq, "input");
  checkRange(page, _rfFreq, 300.0f, 1000.0f, "Outside the usable band");

  static const char* const PIN_CAPTIONS[] = { "SCK", "MISO", "MOSI", "SS", "GDO0", "GDO2" };
  JsonObject pins = arrayComponent(page, _rfPins, "input", W_PIN);
  JsonArray captions = pins.createNestedArray(F("captions"));
  for (uint8_t i = 0; i < 6; i++) captions.add(PIN_CAPTIONS[i]);
  checkValidator(page, _rfPins, "distinct", "The same pin is used twice");

  // Channel -> segment mapping. The output reads the rendered colour of a segment, so it
  // keeps running without a stream.
  JsonObject outRows = arrayComponent(page, _outSeg, "input", W_DROPDOWN);
  outRows[F("captionEach")] = F("CH$i");
  option(outRows, "-", -1);
  for (uint8_t s = 0; s < strip.getSegmentsNum(); s++) {
    const Segment& seg = strip.getSegment(s);
    char label[28];
    snprintf_P(label, sizeof(label), PSTR("SEG%u (%u-%u)"), (unsigned)s,
               (unsigned)seg.start, (unsigned)(seg.stop > seg.start ? seg.stop - 1 : seg.start));
    option(outRows, label, (int16_t)s);
  }
  hint(page, _outSeg, -1, HINT_INFO,
       "<b>Mirror of the input half.</b> Each output channel sends the colour of one segment, so the output also runs without a stream.");

  // Unmapped rows stay in the form (their value is submitted either way) and a small
  // control brings them back, so the list stays short without losing the ability to map
  // a channel.
  JsonObject fold = component(page, "#outFold", "display", W_FOLD);
  fold.createNestedArray(F("members")).add(_outSeg);
  foldLabels(fold, "+ $n unused", "- hide unused");
#endif

  // --- preset control and live status -------------------------------------
  // Both belong to the output half and read the info rows that are compiled in under the same
  // condition. The grid additionally needs published preset keys.
#if RESONANCER_ENABLE_RF
  if (oemKeyCount() > 0) {
    JsonObject grid = oemGrid(page, "#oem", nullptr, "oem");
    grid[F("heading")] = F("OEM preset control");
    // A preset can only be sent while the output is actually running.
    rule(page, "status", OP_NE, "Running", "#oem", PROP_EDITABLE, false, "The output is not running");
  }

  // Live device state: shown to the user and fed back into the rules above.
  JsonObject status = component(page, "#status", "display", W_STATUS);
  pollField(status, "Output", "u.Output.0", "status");
  pollField(status, "Preset", "u.Preset.0");
#endif
}
