/*
 * Embed resonancer_uikit.js into a C++ header.
 *
 * The library is written as a real JavaScript file so it can be linted, unit tested and
 * read in a browser dev tools session; the firmware needs it as a PROGMEM string that
 * appendConfigData() streams to the settings page. This tool is the bridge between the
 * two, and test/header.test.js fails when the committed header is out of date.
 *
 * Usage:
 *   node usermods/Resonancer/tools/uikit_header.js          # regenerate
 *   node usermods/Resonancer/tools/uikit_header.js --check   # exit 1 when stale
 */
