/*
 * resonancer_uikit.js - data driven form engine for a WLED usermod settings page.
 *
 * The engine turns a component table plus a rule table into the three properties a
 * form element can have - visible, editable, required - and applies them through a
 * small adapter interface. Everything except the adapter is a pure function, so the
 * engine is unit tested without a browser (see test/uikit.test.js) and additionally
 * against a real settings page markup fixture (see test/page.test.js).
 *
 * Why the state is derived instead of rendered: WLED generates the settings markup on
 * its own (wled00/data/settings_um.htm, addField()) and posts the whole form back on
 * Save. A usermod therefore cannot own the controls; it adopts the generated rows and
 * annotates them. Deriving the three properties from the current values is what turns
 * that annotation into data instead of a pile of hand written event handlers.
 *
 * ---------------------------------------------------------------------------
 * Page description (built by the C++ side, see resonancer_uikit.cpp)
 * ---------------------------------------------------------------------------
 *
 *   {
 *     anchor: 'outputEnabled',        // field used to find the usermod's <div class="sec">
 *     values: { status: 'Running' },  // extra state that is not a form field
 *     components: [ {
 *        id:      'rfFreq',           // exact HTML form field name, arrays keep '[]'
 *        kind:    'input',            // 'input' | 'action' | 'display'
 *        widget:  'auto',             // 'auto'|'pin'|'dropdown'|'heading'|'hint'|'fold'|'status'|'grid'
 *        array:   false,              // field holds one entry per HTML element
 *        label:   'Frequency',        // caption override (optional)
 *        heading: 'Output',           // subsection heading inserted before the row
 *        position:'before'|'after',   // where the heading/attached nodes go
 *        options: [{ label:'Serial', value:0, disabled:false }],   // widget 'dropdown'
 *        members: ['outSeg[]'],       // widget 'fold': rows that fold away
 *        buttons: [{ key:'red', label:'Red', color:0, span:1 }],    // widget 'grid'
 *        payload: { Resonancer:{ oem:'$key' } },                    // widget 'grid'/'action'
 *        poll:    { url:'/json/info', every:1000,
 *                   fields:[{ label:'Output', path:'um.Resonancer.output' }] }
 *     } ],
 *     rules: [ {                      // restricting rules, see semantics below
 *        when:  { key:'comm', op:'eq', value:1 },   // or { key, prop, op, value }
 *        target:'udpPort', prop:'visible', value:false, reason:'UDP only'
 *     } ],
 *     checks: [ {                     // validation, see validate()
 *        target:'rfFreq', kind:'range', min:300, max:1000, message:'Out of band'
 *     } ],
 *     hints: [ { id:'bleCoexist', index:1, level:'w', text:'One radio for both.' } ]
 *   }
 *
 * Rule semantics are monotonic (fail safe): a rule may only restrict.
 *   - visible:  only value === false takes effect, combined with AND
 *   - editable: only value === false takes effect, combined with AND
 *   - required: only value === true  takes effect, combined with OR
 * A rule that would loosen a property is ignored, so the outcome never depends on the
 * order of the rule table. "Show only while X" is written as a hide rule whose
 * condition is negated (op 'ne' / 'false' / 'notin').
 *
 * A hidden component is never required and never validated: keeping it required would
 * make the browser block Save with no visible feedback, because the core submit path is
 * `if (d.Sf.checkValidity()) d.Sf.submit()` and checkValidity() renders nothing.
 *
 * ---------------------------------------------------------------------------
 * Adapter interface (implemented by wledAdapter() below, replaceable for tests)
 * ---------------------------------------------------------------------------
 *   elements(component)            -> array of elements carrying the field name
 *   setVisible(component, visible)
 *   setEditable(component, editable)
 *   setRequired(component, required)
 *   setValidity(component, message)   // '' clears
 */
