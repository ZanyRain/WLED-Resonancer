	'use strict';

	// Fixed point passes: with ~30 components re-evaluating the whole table is cheaper
	// than sorting it into a dependency graph.
	const MAX_PASSES = 3;

	const DEFAULT_BASE = { visible: true, editable: true, required: false };

	const REASON_PRIORITY = ['visible', 'editable', 'required'];

	// =========================================================================
	// pure: value helpers
	// =========================================================================

	/** Number or null. Booleans become 0/1 so a checkbox can be compared numerically. */
	function num(v) {
		if (typeof v === 'number') return Number.isFinite(v) ? v : null;
		if (typeof v === 'boolean') return v ? 1 : 0;
		if (typeof v === 'string' && v.trim() !== '') {
			const n = Number(v);
			if (Number.isFinite(n)) return n;
		}
		return null;
	}

	/** Compare a form value with a rule value: numerically when both sides are numeric. */
	function same(a, b) {
		const na = num(a), nb = num(b);
		if (na !== null && nb !== null) return na === nb;
		return a === b;
	}

	function truthy(v) {
		return v === true || v === 1 || v === '1' || v === 'true';
	}

	function present(v) {
		return v !== undefined && v !== null && v !== '';
	}

	/** Split a comma separated value list, used by the 'in' / 'notin' operators. */
	function list(v) {
		if (Array.isArray(v)) return v;
		if (typeof v === 'string') return v.split(',').map((s) => s.trim()).filter((s) => s !== '');
		return [];
	}

	// =========================================================================
	// pure: conditions
	// =========================================================================

	/** Test one condition against the current values and the previous derivation pass. */
	function condMet(cond, ctx) {
		if (!cond) return true;
		const actual = cond.prop ? (ctx.matrix[cond.key] ? ctx.matrix[cond.key][cond.prop] : undefined)
		                         : ctx.values[cond.key];
		switch (cond.op) {
			case 'eq':      return same(actual, cond.value);
			case 'ne':      return !same(actual, cond.value);
			case 'in':      return list(cond.value).some((v) => same(actual, v));
			case 'notin':   return !list(cond.value).some((v) => same(actual, v));
			case 'true':    return truthy(actual);
			case 'false':   return !truthy(actual);
			case 'ge':      return num(actual) !== null && num(actual) >= num(cond.value);
			case 'gt':      return num(actual) !== null && num(actual) >  num(cond.value);
			case 'le':      return num(actual) !== null && num(actual) <= num(cond.value);
			case 'lt':      return num(actual) !== null && num(actual) <  num(cond.value);
			case 'exists':  return present(actual);
			case 'missing': return !present(actual);
			case 'active':  return ctx.activeKey === cond.key;   // the field the user just touched
			default:        return false;                        // unknown op never matches
		}
	}

	// =========================================================================
	// pure: derive the three properties
	// =========================================================================

	/**
	 * Apply one restricting rule to a component state.
	 * Loosening rules are ignored, so rule order can never change the outcome.
	 * @returns true when the rule actually restricted the field
	 */
	function applyRule(state, rule) {
		if (!state || !rule) return false;
		if (rule.prop === 'visible' || rule.prop === 'editable') {
			if (rule.value !== false || state[rule.prop] === false) return false;
			state[rule.prop] = false;
		} else if (rule.prop === 'required') {
			if (rule.value !== true || state.required === true) return false;
			state.required = true;
		} else {
			return false;
		}
		return true;
	}

	// A field can be restricted by several rules. Which one explains the restriction is
	// decided by property priority (a hidden field matters more than a locked one), and
	// within one property by rule order.
	function finalize(state, component, reasons) {
		if (component.kind && component.kind !== 'input') state.required = false;
		if (!state.visible) state.required = false;
		state.reason = '';
		for (const prop of REASON_PRIORITY) {
			if (reasons && reasons[prop]) { state.reason = reasons[prop]; break; }
		}
	}

	function cloneMatrix(matrix) {
		const out = {};
		for (const id in matrix) out[id] = Object.assign({}, matrix[id]);
		return out;
	}

	function sameMatrix(a, b) {
		const ka = Object.keys(a), kb = Object.keys(b);
		if (ka.length !== kb.length) return false;
		for (const id of ka) {
			const x = a[id], y = b[id];
			if (!y) return false;
			if (x.visible !== y.visible || x.editable !== y.editable ||
			    x.required !== y.required || x.reason !== y.reason) return false;
		}
		return true;
	}

	/**
	 * Derive { visible, editable, required, reason } for every component.
	 *
	 * @param opts.components component table
	 * @param opts.rules      rule table
	 * @param opts.values     current values (see values())
	 * @param opts.activeKey  field the user just touched, may be null
	 * @returns {{matrix: Object, passes: number, converged: boolean}}
	 */
	function derive(opts) {
		const components = (opts && opts.components) || [];
		const rules = (opts && opts.rules) || [];
		const values = (opts && opts.values) || {};
		const activeKey = (opts && opts.activeKey) || null;

		let matrix = {};
		let converged = false;
		let pass = 0;

		for (; pass < MAX_PASSES; pass++) {
			// Every pass starts from the declared defaults, so the result never depends
			// on the previous pass having partially applied rules.
			const next = {};
			const reasons = {};
			for (const c of components) {
				next[c.id] = Object.assign({ reason: '' }, DEFAULT_BASE, c.base || {});
				reasons[c.id] = { visible: '', editable: '', required: '' };
			}
			const ctx = { values, matrix, activeKey };
			for (const rule of rules) {
				if (!condMet(rule.when, ctx)) continue;
				const state = next[rule.target];
				if (!state) continue;                     // unknown target: ignore, never throw
				const reason = reasons[rule.target];
				if (applyRule(state, rule) && !reason[rule.prop]) reason[rule.prop] = rule.reason || '';
			}
			for (const c of components) finalize(next[c.id], c, reasons[c.id]);

			if (sameMatrix(next, matrix)) { matrix = next; converged = true; break; }
			matrix = next;
		}

		// A converged run reports the pass it settled on, an unconverged one the cap it hit.
		return { matrix, passes: converged ? pass + 1 : MAX_PASSES, converged };
	}

	// =========================================================================
	// pure: validation
	// =========================================================================

	/**
	 * Named predicates. They are the closed extension point for rules that need more
	 * than a range comparison, e.g. WLED pin ownership. Each one receives the check
	 * and a context with the current values and the component table.
	 */
	const validators = {
		/** List elements that repeat a value, e.g. two output channels on one pin. */
		distinct(ctx, check) {
			const seen = [], dup = [];
			for (const v of list(ctx.values[check.target])) {
				if (!present(v) || Number(v) < 0) continue;
				if (seen.indexOf(String(v)) >= 0) dup.push(v);
				else seen.push(String(v));
			}
			return dup.length ? (check.message || 'Value used twice') : '';
		},
	};

	function evalCheck(check, ctx) {
		const value = ctx.values[check.target];
		if (check.when && !condMet(check.when, ctx)) return '';
		switch (check.kind) {
			case 'range': {
				const n = num(value);
				if (n === null) return '';
				if (check.min !== undefined && n < num(check.min)) return check.message || 'Below the minimum';
				if (check.max !== undefined && n > num(check.max)) return check.message || 'Above the maximum';
				return '';
			}
			case 'pattern': {
				if (value === undefined || value === null) return '';
				let re = null;
				try { re = new RegExp(check.pattern, check.flags || ''); } catch (e) { return ''; }
				return re.test(String(value)) ? '' : (check.message || 'Malformed value');
			}
			case 'enum':
				return list(check.values).some((v) => same(value, v)) ? '' : (check.message || 'Unsupported value');
			case 'notEmpty':
				return present(value) ? '' : (check.message || 'Required');
			case 'validator': {
				const fn = validators[check.name];
				return fn ? fn(ctx, check) : '';
			}
			default:
				return '';
		}
	}

	/**
	 * Run the element level checks.
	 *
	 * A component that is hidden is never validated, and an empty value only fails when
	 * the derivation marked the field required, so an untouched optional field cannot
	 * block the Save button.
	 *
	 * @returns {{validity: Object, ok: boolean}} validity maps component id -> message
	 */
	function validate(opts) {
		const checks = (opts && opts.checks) || [];
		const components = (opts && opts.components) || [];
		const matrix = (opts && opts.matrix) || {};
		const values = (opts && opts.values) || {};
		const activeKey = (opts && opts.activeKey) || null;
		const ctx = { values, matrix, activeKey };
		const validity = {};
		let ok = true;

		for (const check of checks) {
			const message = evalCheck(check, ctx);
			if (!message) continue;
			for (const id of (Array.isArray(check.target) ? check.target : [check.target])) {
				const state = matrix[id];
				const c = components.find((x) => x.id === id);
				if (!state || !state.visible || (c && c.kind !== 'input')) continue;
				if (!present(values[id]) && !state.required) continue;   // optional and empty
				if (!validity[id]) validity[id] = message;
				ok = false;
			}
		}
		return { validity, ok };
	}

	// =========================================================================
	// pure: values
	// =========================================================================

	/** Coerce one element to a form value: checkboxes read their checked state. */
	function coerce(el) {
		if (!el) return undefined;
		if (el.type === 'checkbox') return !!el.checked;
		if (el.tagName === 'SELECT') {
			const n = num(el.value);
			return n === null ? el.value : n;
		}
		if (el.type === 'number' || el.type === 'int') return num(el.value);
		return el.value;
	}

	/**
	 * Read the current value of every input component.
	 *
	 * The hidden type sentinel WLED emits next to each scalar field is skipped: it holds
	 * the JavaScript type of the field, never its value. An unchecked checkbox pairs with
	 * a hidden field whose value is the string "false", which is why reading
	 * element.value instead of element.checked would be wrong.
	 *
	 * @param extra additional values that are not form fields (device state)
	 */
	function values(components, adapter, extra) {
		const out = {};
		for (const c of (components || [])) {
			if (c.kind && c.kind !== 'input') continue;
			const all = (adapter && adapter.elements ? adapter.elements(c) : null) || [];
			const real = all.filter((e) => e && e.type !== 'hidden');
			if (!real.length) { out[c.id] = undefined; continue; }
			if (c.array === true || real.length > 1) out[c.id] = real.map(coerce);
			else out[c.id] = coerce(real[0]);
		}
		if (extra) for (const k in extra) out[k] = extra[k];
		return out;
	}

	// =========================================================================
	// pure: apply
	// =========================================================================

	/**
	 * Push the derivation result to the adapter, touching only what changed.
	 *
	 * @returns array of applied changes, useful for tests and for a debug log.
	 */
	function applyState(opts) {
		const components = (opts && opts.components) || [];
		const matrix = (opts && opts.matrix) || {};
		const validity = (opts && opts.validity) || {};
		const prev = (opts && opts.prev) || null;
		const prevValidity = (opts && opts.prevValidity) || null;
		const adapter = opts && opts.adapter;
		const applied = [];
		if (!adapter) return applied;

		for (const c of components) {
			const now = matrix[c.id];
			if (!now) continue;
			const was = prev ? prev[c.id] : null;

			if (!was || was.visible !== now.visible) {
				adapter.setVisible(c, now.visible);
				applied.push({ id: c.id, prop: 'visible', value: now.visible });
			}
			if (!was || was.editable !== now.editable) {
				adapter.setEditable(c, now.editable);
				applied.push({ id: c.id, prop: 'editable', value: now.editable });
			}
			if (!was || was.required !== now.required) {
				adapter.setRequired(c, now.required);
				applied.push({ id: c.id, prop: 'required', value: now.required });
			}

			const message = now.visible ? (validity[c.id] || '') : '';
			const before = prevValidity ? (prevValidity[c.id] || '') : null;
			if (before === null || before !== message) {
				adapter.setValidity(c, message);
				applied.push({ id: c.id, prop: 'validity', value: message });
			}
		}
		return applied;
	}

	// =========================================================================
	// engine: read, derive, validate, apply
	// =========================================================================

	/**
	 * Stateful wrapper. It keeps the previous matrix and validity so that only real
	 * changes reach the DOM, which also makes repeated calls idempotent.
	 */
	function engine(opts) {
		const components = (opts && opts.components) || [];
		const rules = (opts && opts.rules) || [];
		const checks = (opts && opts.checks) || [];
		const adapter = opts && opts.adapter;
		let prev = null, prevValidity = null, passes = 0, converged = true;

		return {
			components, rules, checks,
			values: (extra) => values(components, adapter, extra),
			matrix: () => prev,
			validity: () => prevValidity,
			/**
			 * @param activeKey field the user just touched (optional)
			 * @param extra     non form values, e.g. device state (optional)
			 */
			refresh(activeKey, extra) {
				const v = values(components, adapter, extra);
				const d = derive({ components, rules, values: v, activeKey: activeKey || null });
				const check = validate({ components, checks, matrix: d.matrix, values: v, activeKey: activeKey || null });
				const applied = applyState({
					components, matrix: d.matrix, validity: check.validity,
					prev, prevValidity, adapter,
				});
				prev = cloneMatrix(d.matrix);
				prevValidity = check.validity;
				passes = d.passes;
				converged = d.converged;
				return { values: v, matrix: prev, validity: prevValidity, ok: check.ok, applied, passes, converged };
			},
			converged: () => converged,
			passes: () => passes,
		};
	}

	/** Ids whose state may change when activeKey is edited - for debug output and logs. */
	function dependents(activeKey, rules) {
		const out = [];
		for (const r of (rules || [])) {
			if (!r || !r.when || r.when.key !== activeKey) continue;
			if (out.indexOf(r.target) < 0) out.push(r.target);
		}
		return out;
	}

	// =========================================================================
	// DOM runtime: the row surgery WLED's generated markup needs
	// =========================================================================

	/**
	 * WLED writes every field of a usermod straight into one <div class="sec"> with no
	 * per row wrapper, so a row is defined by what surrounds the control: the caption
	 * text before it, the text nodes (units) up to the next <br>, that <br>, and the
	 * hint boxes attached after it. Hiding a row means hiding all of those pieces, and
	 * text nodes have to be wrapped in a span before they can be hidden at all.
	 */
	function createDom(root, doc) {
		const attached = {};        // component id -> [extra nodes that belong to the row]
		let section = null;         // the usermod's own <div class="sec">

		function byName(name) {
			if (!name) return [];
			const list = doc.getElementsByName(name);
			return list ? Array.prototype.slice.call(list) : [];
		}

		function controls(name) {
			return byName(name).filter((e) => e.type !== 'hidden');
		}

		function rowEnd(x) {
			let n = x;
			while (n && n.nodeName !== 'BR') n = n.nextSibling;
			return n || x;
		}

		/** Nearest caption before the control, skipping other rows' line breaks. */
		function capNode(x) {
			let a = x.previousSibling;
			while (a && a.nodeName !== 'BR') {
				if (a.nodeType === 3 && a.data && a.data.trim()) return a;
				if (a.nodeType === 1 && a.nodeName === 'SPAN' && a.className.indexOf('rn') < 0) return a;
				a = a.previousSibling;
			}
			return null;
		}

		function capText(c, txt) {
			if (!c) return;
			const s = ' ' + txt + ' ';
			if (c.nodeType === 3) c.data = s; else c.textContent = s;
		}

		function setCap(name, txt) {
			for (const e of controls(name)) capText(capNode(e), txt);
		}

		function capEach(name, fn) {
			let r = 0;
			for (const e of controls(name)) { capText(capNode(e), fn(r)); r++; }
		}

		/** A caption must be an element before it can be hidden. */
		function capHide(x, display) {
			let c = capNode(x);
			if (!c) return;
			if (c.nodeType === 3) {
				const sp = doc.createElement('span');
				c.parentNode.insertBefore(sp, c);
				sp.appendChild(c);
				c = sp;
			}
			c.style.display = display;
		}

		/** Trailing units ("MHz") belong to the row and have to follow it. */
		function unitHide(x, display) {
			let n = x.nextSibling;
			while (n && n.nodeName !== 'BR') {
				const nx = n.nextSibling;
				if (n.nodeType === 3 && n.data.trim()) {
					const sp = doc.createElement('span');
					n.parentNode.insertBefore(sp, n);
					sp.appendChild(n);
					sp.style.display = display;
				}
				n = nx;
			}
		}

		function rowShow(x, on) {
			const display = on ? '' : 'none';
			x.style.display = display;
			capHide(x, display);
			unitHide(x, display);
			const br = rowEnd(x);
			if (br && br.nodeName === 'BR') br.style.display = display;
		}

		/** Extra nodes attached to a row (hints, errors) follow its visibility. */
		function attach(id, node) {
			if (!node) return node;
			const list = attached[id] || (attached[id] = []);
			list.push(node);
			return node;
		}

		function attachedRows(id) {
			return attached[id] || [];
		}

		function showAttached(id, on) {
			const display = on ? '' : 'none';
			for (const n of attachedRows(id)) n.style.display = display;
		}

		/** Insert a node after the row of a field, i.e. below its control. */
		function appendToRow(name, node, index) {
			const els = controls(name);
			if (!els.length) return null;
			const el = (index === undefined || index < 0) ? els[els.length - 1] : els[index];
			if (!el) return null;
			let last = attachedRows(name).length ? attachedRows(name)[attachedRows(name).length - 1] : rowEnd(el);
			last.parentNode.insertBefore(node, last.nextSibling);
			return node;
		}

		/** Subsection heading, the same markup the built-in settings pages use. */
		function insertHeading(name, title) {
			const els = byName(name);
			let el = null;
			for (const e of els) { if (e.type !== 'hidden') { el = e; break; } }
			if (!el) return false;
			const cap = capNode(el);
			const anchor = cap || el;
			const hr = doc.createElement('hr');
			hr.className = 'sml';
			const p = doc.createElement('p');
			const u = doc.createElement('u');
			u.textContent = title;
			p.appendChild(u);
			anchor.parentNode.insertBefore(hr, anchor);
			anchor.parentNode.insertBefore(p, anchor);
			return true;
		}

		/** The dropdown converter marks converted rows with the 'pin' class. */
		function dropPinClass(name) {
			for (const e of byName(name)) if (e.classList) e.classList.remove('pin');
		}

		function markSection(anchor) {
			const el = controls(anchor)[0] || byName(anchor)[0];
			const sec = el && el.closest ? el.closest('.sec') : null;
			if (sec) sec.classList.add('rsec');
			section = sec;
			return sec;
		}

		/** Widgets this usermod owns live at the end of its own section. */
		function appendToSection(node) {
			if (!section) return null;
			section.appendChild(node);
			return node;
		}

		return {
			byName, controls, rowEnd, capNode, capText, setCap, capEach, capHide, unitHide,
			rowShow, attach, attachedRows, showAttached, appendToRow, appendToSection,
			insertHeading, dropPinClass, markSection,
			section: () => section,
		};
	}

