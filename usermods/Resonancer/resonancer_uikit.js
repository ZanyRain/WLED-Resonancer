	function wledAdapter(root) {
		// Accept a document (nodeType 9) or any node inside one.
		const doc = (root && root.nodeType === 9) ? root
			: (root && root.ownerDocument) || (typeof document !== 'undefined' ? document : null);
		const dom = createDom(root, doc);

		/** Mark a node as ours so a re-run of the settings script does not duplicate it. */
		function mine(node, kind) {
			if (node && node.setAttribute) node.setAttribute('data-ukit', kind);
			return node;
		}

		return {
			doc, dom,
			elements: (c) => dom.byName(c.id),

			setVisible(c, visible) {
				for (const el of dom.controls(c.id)) dom.rowShow(el, visible);
				dom.showAttached(c.id, visible);
			},

			/** Per element visibility, for repeated rows handled by a fold widget. */
			setVisibleAt(id, index, visible) {
				const el = dom.controls(id)[index];
				if (el) dom.rowShow(el, visible);
			},

			setEditable(c, editable) {
				for (const el of dom.controls(c.id)) {
					if (el.tagName === 'SELECT') {
						// A disabled control is not submitted, so the select stays enabled
						// and only its alternatives are locked (the core does the same for
						// pins owned by another module).
						for (const opt of el.options) opt.disabled = !editable && !opt.selected;
					} else if (el.type === 'checkbox') {
						// No readonly for checkboxes; a disabled one is dropped from the
						// form post, which is only safe with the containsKey guards in
						// readFromConfig().
						el.disabled = !editable;
					} else {
						el.readOnly = !editable;
					}
				}
			},

			setRequired(c, required) {
				for (const el of dom.controls(c.id)) el.required = !!required;
			},

			setValidity(c, message) {
				const msg = message || '';
				for (const el of dom.controls(c.id)) {
					if (el.setCustomValidity) el.setCustomValidity(msg);
				}
				// The reason is rendered next to the row, because checkValidity() shows
				// nothing on its own: without this the Save button would fail silently.
				let box = null;
				for (const n of dom.attachedRows(c.id)) {
					if (n.getAttribute && n.getAttribute('data-ukit') === 'error') { box = n; break; }
				}
				if (!msg) {
					if (box) box.style.display = 'none';
					return;
				}
				if (!box) {
					box = mine(doc.createElement('span'), 'error');
					box.className = 'rn e';
					if (!dom.appendToRow(c.id, box)) return;
					dom.attach(c.id, box);
				}
				box.textContent = msg;
				box.style.display = '';
			},
		};
	}

