	const LEVELS = { i: 'i', g: 'g', w: 'w', e: 'e' };

	/**
	 * Pin rows.
	 *
	 * The core's pinDD() only converts fields whose name contains "pin", so a usermod
	 * field called rfPins stays a plain number input and loses the pin owner information.
	 * This mirrors what the core does for its own pin fields: one option per GPIO, used
	 * pins named and disabled, read-only pins marked, and the 'pin' class kept so the
	 * core's own UI() handler keeps the ownership in sync between rows.
	 */
	function mountPin(adapter, comp, root) {
		const dom = adapter.dom;
		if (!adapter.doc || typeof root.addDropdown !== 'function') return null;
		const page = root.d || {};
		const maxGpio = present(page.max_gpio) ? page.max_gpio : 50;
		const pinsData = page.pinsData || [];
		const reserved = page.rsvd || [];
		const readOnly = page.ro_gpio || [];
		const ownerName = typeof root.getOwnerName === 'function' ? root.getOwnerName : () => '';
		const control = typeof root.addOption === 'function' ? root.addOption : null;
		const made = [];

		const wanted = dom.controls(comp.id).length;
		for (let i = 0; i < wanted; i++) {
			const before = dom.controls(comp.id)[i];
			const current = before ? parseInt(before.value, 10) : NaN;
			const sel = root.addDropdown(comp.id, i);   // the numeric argument keeps the pin class
			if (!sel || !control) break;
			made.push(sel);
			for (let gpio = -1; gpio < maxGpio; gpio++) {
				if (gpio > -1 && reserved.indexOf(gpio) >= 0) continue;
				const info = pinsData.find ? pinsData.find((p) => p.p === gpio) : null;
				const used = gpio > -1 && info && info.a && gpio !== current;   // not "our" pin
				let text = (gpio === -1) ? 'unused' : String(gpio);
				if (used) text += ' (' + ownerName(info.o, info.t, info.n) + ')';
				if (gpio > -1 && readOnly.indexOf(gpio) >= 0) text += ' (input only)';
				const opt = control(sel, text, gpio);
				if (!opt) continue;
				if (gpio === current) opt.selected = true;
				else if (used) opt.disabled = true;
			}
		}
		return made;
	}

	/**
	 * Fold: repeated rows (one per segment or channel) whose untouched entries are hidden
	 * behind a small reveal control, so the list stays short without losing the ability
	 * to edit an entry.
	 */
	function mountFold(adapter, comp) {
		const dom = adapter.dom;
		const doc = adapter.doc;
		if (!doc) return null;
		const members = comp.members || [];
		const state = { open: false };

		const control = doc.createElement('button');
		control.type = 'button';
		control.className = 'btn btn-xs';
		control.setAttribute('data-ukit', 'fold');
		if (!dom.appendToSection(control)) return null;
		dom.attach(comp.id, control);

		function sync(host) {
			// The host component decides first: while it is hidden (the output is off, for
			// example) the fold hides its rows instead of revealing the mapped ones.
			if (host && host.visible === false) {
				for (const id of members) {
					const rows = dom.controls(id);
					for (let i = 0; i < rows.length; i++) adapter.setVisibleAt(id, i, false);
				}
				control.style.display = 'none';
				return;
			}
			let hidden = 0;
			for (const id of members) {
				// A repeated field has one row per element, so the fold works element by
				// element: an entry that was never mapped hides, a mapped one stays.
				const els = dom.controls(id);
				for (let i = 0; i < els.length; i++) {
					const used = String(els[i].value) !== '-1' && String(els[i].value) !== '';
					const show = used || state.open;
					if (!show) hidden++;
					adapter.setVisibleAt(id, i, show);
				}
			}
			const label = state.open
				? (comp.labelOpen || '- hide unused')
				: (comp.label || '+ $n unused').replace('$n', hidden);
			control.textContent = label;
			// A reveal control with nothing to reveal is noise: the whole control only
			// exists while something is folded away or while it is open.
			control.style.display = (hidden === 0 && !state.open) ? 'none' : '';
		}

		control.addEventListener('click', () => { state.open = !state.open; sync(); });
		return { sync, control };
	}

	/**
	 * Status: values the form does not hold, read from the device while the page is
	 * open. Used for the live output state and for the result of the last preset
	 * command, and it feeds those values back into the rule values so a rule can depend
	 * on the device state.
	 */
	function mountStatus(adapter, comp, transport) {
		const dom = adapter.dom;
		const doc = adapter.doc;
		if (!doc) return null;
		const fields = (comp.poll && comp.poll.fields) || [];
		const rows = [];
		const live = {};

		const box = doc.createElement('span');
		box.className = 'ukit-status';
		box.setAttribute('data-ukit', 'status');
		for (const f of fields) {
			const line = doc.createElement('span');
			line.className = 'rn i';
			// Hidden until the device has something to report: an empty "Preset: -" row
			// is noise, and the box disappears entirely while nothing is known.
			line.style.display = 'none';
			box.appendChild(line);
			rows.push({ node: line, field: f });
			if (f.value) live[f.value] = undefined;
		}
		if (!dom.appendToSection(box)) return null;
		dom.attach(comp.id, box);

		return {
			/** Read the device state and render it; returns the values for the rules. */
			async fetch() {
				const info = await transport.getInfo();
				if (!info) return live;
				let shown = 0;
				for (const r of rows) {
					const v = transport.pluck(info, r.field.path);
					if (present(v)) {
						r.node.textContent = r.field.label + ': ' + v;
						r.node.style.display = '';
						shown++;
					} else {
						r.node.style.display = 'none';
					}
					if (r.field.value) live[r.field.value] = v;
				}
				box.style.display = shown ? '' : 'none';
				return live;
			},
			values: () => live,
			box,
		};
	}

	/**
	 * Action grid: trigger buttons built from the registry. Each button posts its own
	 * payload; the result is read back through the status poll, so a click never reloads
	 * the page and a refusal is visible instead of silent.
	 */
	function mountGrid(adapter, comp, transport, onDone) {
		const dom = adapter.dom;
		const doc = adapter.doc;
		if (!doc) return null;
		const wrap = doc.createElement('span');
		wrap.className = 'ukit-grid';
		wrap.setAttribute('data-ukit', 'grid');
		wrap.style.cssText = 'display:inline-flex;flex-wrap:wrap;gap:2px;align-items:center;justify-content:center';
		const buttons = [];

		// The reason line is what turns "the click did nothing" into "the output is not
		// running": it also reports the outcome of a command that was posted.
		const note = doc.createElement('span');
		note.className = 'rn w';
		note.setAttribute('data-ukit', 'grid-note');
		note.style.display = 'none';

		for (const b of (comp.buttons || [])) {
			const btn = doc.createElement('button');
			btn.type = 'button';
			btn.className = 'btn btn-xs';
			btn.textContent = b.label;
			btn.title = b.title || b.label;
			if (comp.colors && comp.colors[b.color]) btn.style.borderLeftColor = comp.colors[b.color];
			if (b.span && b.span > 1) btn.style.gridColumn = 'span ' + b.span;
			btn.addEventListener('click', async () => {
				const payload = substitute(comp.payload, '$key', b.key);
				btn.disabled = true;
				const res = await transport.postState(payload);
				btn.disabled = false;
				btn.classList.toggle('ukit-err', res === false);
				// Immediate feedback: the device result follows through the status poll.
				setNote(res === false ? 'e' : 'g', res === false ? 'Request failed' : 'Sent: ' + b.label, 2000);
				if (typeof onDone === 'function') onDone(b.key, res);
			});
			wrap.appendChild(btn);
			buttons.push({ key: b.key, node: btn });
		}

		// The preset grid has no config field behind it, so it brings its own heading
		// instead of inserting one in front of a generated row.
		let host = wrap;
		if (comp.heading) {
			host = doc.createElement('span');
			const hr = doc.createElement('hr');
			hr.className = 'sml';
			const p = doc.createElement('p');
			const u = doc.createElement('u');
			u.textContent = comp.heading;
			p.appendChild(u);
			host.appendChild(hr);
			host.appendChild(p);
			host.appendChild(wrap);
		}
		host.appendChild(note);
		if (!dom.appendToSection(host)) return null;
		dom.attach(comp.id, host);

		let noteTimer = null;
		function setNote(level, text, clearAfterMs) {
			if (noteTimer) { clearTimeout(noteTimer); noteTimer = null; }
			if (!text) { note.style.display = 'none'; return; }
			note.className = 'rn ' + (level || 'i');
			note.textContent = text;
			note.style.display = '';
			if (clearAfterMs) noteTimer = setTimeout(() => { note.style.display = 'none'; }, clearAfterMs);
		}

		/**
		 * @param enabled whether a preset may be sent right now
		 * @param reason  why not, shown under the buttons
		 */
		function setEnabled(enabled, reason) {
			for (const b of buttons) b.node.disabled = !enabled;
			if (!enabled) setNote('w', reason || 'The output is not running', 0);
			else if (note.className === 'rn w') setNote(null, '', 0);
		}
		return { setEnabled, wrap, buttons, note: setNote };
	}

	/** Replace $key style placeholders in a payload template. */
	function substitute(template, token, value) {
		if (!template) return null;
		const json = JSON.stringify(template).split(token).join(value);
		try { return JSON.parse(json); } catch (e) { return null; }
	}

	// =========================================================================
	// api: settings page safe transport (never uses main page globals)
	// =========================================================================

	function api(root) {
		const base = (root && root.getURL) ? root.getURL : (p) => p;

		async function postState(payload) {
			if (!payload) return false;
			try {
				const res = await fetch(base('/json/state'), {
					method: 'POST',
					headers: { 'Content-Type': 'application/json' },
					body: JSON.stringify(payload),
				});
				return !!res && res.ok;
			} catch (e) {
				return false;
			}
		}

		async function getInfo() {
			try {
				const res = await fetch(base('/json/info'));
				if (!res || !res.ok) return null;
				return await res.json();
			} catch (e) {
				return null;
			}
		}

		function pluck(obj, path) {
			let cur = obj;
			for (const part of String(path || '').split('.')) {
				if (cur === null || cur === undefined) return undefined;
				cur = cur[part];
			}
			return cur;
		}

		return { postState, getInfo, pluck };
	}

