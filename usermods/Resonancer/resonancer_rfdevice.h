// Pin selector for pins that are not used by a concrete driver.
// Pass RESONANCER_PIN_UNUSED for MISO/SS/GD0/GD2 when the board does not wire them.
constexpr int8_t RESONANCER_PIN_UNUSED = -1;

// Default pin assignment and frequency of the reference board. They only pre-fill
// the settings page and sanity check a stored value; every pin and the frequency
// stay user configurable. The numbers describe the reference hardware, so they are
// defined next to the implementation - by the implementation itself, or by the
// stub in a build without an output device (see the two definitions of these
// symbols). The implementation owns this bus and starts it itself, so the pins must
// not collide with a SPI based LED bus.
extern const int8_t RESONANCER_DEFAULT_SCK;
extern const int8_t RESONANCER_DEFAULT_MISO;
extern const int8_t RESONANCER_DEFAULT_MOSI;
extern const int8_t RESONANCER_DEFAULT_SS;
extern const int8_t RESONANCER_DEFAULT_GD0;
extern const int8_t RESONANCER_DEFAULT_GD2;
extern const float  RESONANCER_DEFAULT_RF_FREQ;   // MHz

// Runtime tunables. Everything the implementation needs beyond this is fixed in the
// implementation.
// AI: below section was generated by an AI
struct RFRuntimeConfig {
  float rf_freq = 0;   // MHz, initialised from RESONANCER_DEFAULT_RF_FREQ
};

/*
 * 8 bit colour triple handed to the output device.
 */
struct RgbColor {
  uint8_t r;
  uint8_t g;
  uint8_t b;
};

/*
 * Result of the (upper layer) licence check. The output device turns the licence
 * state into its own behaviour, so an unlicensed device can be de-initialised from
 * the implementation side if required.
 */
enum class AuthResult : uint8_t {
  Ok = 0,           // licence valid
  NotAuthenticated, // no valid licence received yet
  AuthFailed,       // licence rejected
  AuthExpired,      // licence timed out
  RfRestricted,     // regulatory restriction active
};

class RFDevice {
  public:
    virtual ~RFDevice() = default;

    /**
     * @brief Static configuration, called once at start up.
     *
     * @param channelCount number of channels handled by this device (1..10)
     * @param sckPin       SPI clock pin, RESONANCER_PIN_UNUSED when not wired
     * @param misoPin      SPI MISO pin, RESONANCER_PIN_UNUSED when not wired
     * @param mosiPin      SPI MOSI pin, RESONANCER_PIN_UNUSED when not wired
     * @param ssPin        SPI chip select pin
     * @param gd0Pin       device interrupt pin, RESONANCER_PIN_UNUSED when not wired
     * @param gd2Pin       device status pin, RESONANCER_PIN_UNUSED when not wired
     * @retval true when the configuration was accepted
     */
    virtual bool InitConfig(uint8_t channelCount, int8_t sckPin, int8_t misoPin, int8_t mosiPin,
                            int8_t ssPin, int8_t gd0Pin, int8_t gd2Pin) = 0;

    /** @brief Enable the device and enter the operating state. @retval true on success */
    virtual bool DeviceInit() = 0;

    /** @brief Runtime parameter update that does not require re-configuration. */
    virtual void changeRuntimeConfig(const RFRuntimeConfig& cfg) = 0;

    /**
     * @brief Submit one packet of RGB data.
     * @param channelCount number of entries in arr (never exceeds the configured count)
     * @param arr          colour array with at least channelCount entries
     */
    virtual void submitRGBPacket(uint8_t channelCount, const RgbColor* arr) = 0;

    /** @brief Push the licence decision (signature validation happens in the upper layer). */
    virtual void setAuthentication(AuthResult result) = 0;

    /** @brief Trigger a device built-in preset colour, index 0..16. */
    virtual void setOemCommand(uint8_t index) = 0;

    /** @brief Disable the device and leave the operating state. */
    virtual void DeviceUnInit() = 0;

    /** @brief True while the previous packet has not reached the radio yet. */
    virtual bool isBusy() const { return false; }

    /** @brief True while a submitted preset has not been transmitted yet. */
    virtual bool isOemPending() const { return false; }

    /** @brief Duration of the last transmission in microseconds, 0 when unknown. */
    virtual uint32_t lastTxMicros() const { return 0; }

    /** @brief How often the device was configured, for diagnostics. */
    virtual uint32_t configCount() const { return 0; }

    /** @brief How long the last transmitted packet waited in the queue, in milliseconds. */
    virtual uint32_t lastQueueMs() const { return 0; }

    /** @brief Number of packets actually handed to the radio. */
    virtual uint32_t txCount() const { return 0; }

    /** @brief Transmissions that needed the full GDO0 extension, i.e. ran long. */
    virtual uint32_t txTimeouts() const { return 0; }

    /** @brief Measured packet rate in packets per second. */
    virtual uint32_t txRate() const { return 0; }

    /** @brief Human readable driver name, used for status reporting. */
    virtual const char* getName() const = 0;

    /** @brief True when the device is currently enabled and operating. */
    virtual bool isActive() const = 0;
};

