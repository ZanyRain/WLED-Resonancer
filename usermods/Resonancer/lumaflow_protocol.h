#include <stddef.h>
#include <stdint.h>

/*
 * LumaFlow serial protocol - frame constants and decoders.
 *
 * This part is intentionally free of any WLED dependency so it can be unit
 * tested on a host and reused by other input transports (UDP, BLE).
 *
 * Wire format (little endian fields, length excludes the framing bytes):
 *
 *   +------+------+--------+-----+-------------+----------+------+
 *   | 0xEB | 0x90 | length | cmd | payload     | checksum | 0xED |
 *   +------+------+--------+-----+-------------+----------+------+
 *
 *   length   = 1 + payload length             (1..128)
 *   checksum = (length + cmd + sum(payload)) & 0xFF
 *
 * Commands:
 *   STREAM (0xD8) : 20 byte payload = 10 channels x 2 bytes
 *                   byte 0 = (function << 4) | red
 *                   byte 1 = (green    << 4) | blue
 *                   every field is a 4 bit value (0..15)
 *   AUTH   (0xE0) : host_time(4, LE) | expire_time(4, LE) | sig_len(1) | signature
 *
 * Reference: LumaFlow host application TLV implementation.
 */
